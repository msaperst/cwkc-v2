const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const Papa = require('papaparse');

const root = path.resolve(__dirname, '..');
const filename = path.join(root, '.cwkc-e2e-results.csv');
const season = JSON.parse(fs.readFileSync(
  path.join(root, 'public/assets/config/season.json'), 'utf8'
));

test.skip(!fs.existsSync(filename),
  'Generate the disposable fixture with python -m scraper.e2e_rehearsal first');

test('synthetic LGL → Sheet → CSV is consumed by real HTML and scores correctly', async ({ page }) => {
  const csv = fs.readFileSync(filename, 'utf8');
  const parsed = Papa.parse(csv, { header: true, skipEmptyLines: true });
  expect(parsed.errors).toHaveLength(0);
  expect(parsed.data).toHaveLength(1);
  const fields = parsed.meta.fields;
  const expected = parsed.data[0];
  expect(fields).toHaveLength(26);
  expect(expected.uva_total_amount).toBe('269.68');
  expect(expected.vt_total_amount).toBe('373.0');
  expect(expected.uva_most_money_families).toBe('264.68');
  expect(expected.vt_most_money_families).toBe('373.0');
  expect(expected.uva_alumni_gatherings).toBe('1');
  expect(expected.vt_hanukkah_photos).toBe('2');

  // Route the exact CSV generated by the Python importer through the browser's
  // actual AJAX→PapaParse→DOM code. Never use the live Pages site.
  let fetched = 0;
  await page.route(/\/assets\/csv\/results\.csv(?:\?|$)/, async route => {
    fetched += 1;
    await route.fulfill({ status: 200, contentType: 'text/csv', body: csv });
  });
  await page.clock.setFixedTime(new Date(new Date(season.start).getTime() + 60_000));
  await page.goto('/', { waitUntil: 'load' });
  await expect(page.locator('#season-dates')).toContainText('from ');
  await expect(page.locator('#countdown-text')).toHaveText('The Cup Ends In');

  await expect(page.locator('#uva_total_amount')).toHaveText('269.68');
  await expect(page.locator('#vt_total_amount')).toHaveText('373.00');
  await expect(page.locator('#uva_most_money_families')).toHaveText('264.68');
  await expect(page.locator('#vt_most_money_families')).toHaveText('373.00');
  await expect(page.locator('#uva_most_individual_donors')).toHaveText('2');
  await expect(page.locator('#vt_most_individual_donors')).toHaveText('2');
  await expect(page.locator('#uva_alumni_gatherings')).toHaveText('1');
  await expect(page.locator('#vt_alumni_gatherings')).toHaveText('1');
  await expect(page.locator('#uva_hanukkah_photos')).toHaveText('1');
  await expect(page.locator('#vt_hanukkah_photos')).toHaveText('2');

  // Derive the winner and point total independently from the actual CSV
  // category values and page weights, not from the page's own sum.
  const rows = await page.locator('#score-areas [data-points]').evaluateAll(
    nodes => nodes.map(node => ({
      category: node.id, points: Number(node.dataset.points),
    }))
  );
  expect(rows).toHaveLength(12);
  let hoo = 0;
  let hokie = 0;
  for (const { category, points } of rows) {
    const left = Number(expected['uva_' + category]);
    const right = Number(expected['vt_' + category]);
    expect(Number.isFinite(left) && Number.isFinite(right)).toBe(true);
    if (left > right) hoo += points;
    if (right > left) hokie += points;
  }
  await expect(page.locator('#hooTotal')).toHaveText(String(hoo));
  await expect(page.locator('#hokieTotal')).toHaveText(String(hokie));
  expect(fetched).toBeGreaterThanOrEqual(1);
  await expect(page).toHaveURL(/^http:\/\/127\.0\.0\.1:8765\//);
});
